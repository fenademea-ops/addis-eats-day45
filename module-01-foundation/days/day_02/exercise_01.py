student_name = "Abel"
age = 22
course = "Software Engineering"
completed_assignments = 8
total_assignments = 10

# Calculate completion percentage
completion_percentage = (completed_assignments / total_assignments) * 100

# Check if completion is greater than 70%
is_above_seventy = completion_percentage > 70

# Print results
print(f"Student: {student_name}")
print(f"Age: {age}")
print(f"Course: {course}")
print(f"Completion: {completion_percentage}%")
print(f"Completed more than 70%: {is_above_seventy}")